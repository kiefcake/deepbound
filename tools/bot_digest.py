"""Digest every autoplay bot log on disk into docs/BOT_FINDINGS.md (2026-11-07, the user: keep what the bots saw for the
future). Re-run after any bot run: python tools/bot_digest.py

For each run: class, floors, per-floor time / guardian time / kills / damage taken / near-downs, the final kit, and every
'??' problem the bot reported. Then every distinct problem across all runs, with counts and the runs it appeared in.
Logs live under Builds/ (not in git), so this file is the durable record.
"""
import os, re, sys, time, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'docs', 'BOT_FINDINGS.md')

FLOOR = re.compile(r'\] F(\d+) floor done in ([\d.]+) min \(guardian ([\d.]+) min\): kills (\d+), dealt (\d+), taken (\d+), downs (\d+), would-have-gone-down (\d+)')
PROBLEM = re.compile(r'\] F(\d+)\s+\?\? (.*)$')
KIT = re.compile(r'\] F\d+ KIT (.*)$')
SOURCE = re.compile(r'damage by source, ([^:]+): (.*)$')
CLASS_IN_PATH = re.compile(r'(Knight|Mage|Cleric|Rogue|Ranger|Flagellant|PlagueDoctor|plaguedoctor|flagellant|ranger|rogue|cleric|mage|knight)')


def norm(problem):
    """A problem's shape, numbers and positions blanked, so repeats group together."""
    p = re.sub(r'\(-?[\d.]+, -?[\d.]+, -?[\d.]+\)', '(pos)', problem)
    p = re.sub(r'-?\d+(\.\d+)?', '#', p)
    return p[:160]


def runs():
    for base in ('Builds',):
        for dirpath, _, files in os.walk(os.path.join(ROOT, base)):
            for f in files:
                if f.startswith('autoplay') and f.endswith('.txt'):
                    yield os.path.join(dirpath, f)


def main():
    rows, groups = [], collections.defaultdict(list)
    for path in sorted(runs(), key=os.path.getmtime):
        rel = os.path.relpath(path, ROOT).replace('\\', '/')
        try:
            text = open(path, encoding='utf-8', errors='replace').read().splitlines()
        except OSError:
            continue
        floors, problems, kit = [], [], None
        cls = None
        for line in text:
            m = FLOOR.search(line)
            if m:
                floors.append(tuple(float(x) if '.' in x else int(x) for x in m.groups()))
            m = PROBLEM.search(line)
            if m:
                problems.append((int(m.group(1)), m.group(2).strip()))
            m = KIT.search(line)
            if m:
                kit = m.group(1)
            if cls is None and ' KIT ' in line:
                cls = line.split(' KIT ', 1)[1].split(' ', 1)[0]
        if cls is None:
            m = CLASS_IN_PATH.search(rel)
            cls = m.group(1) if m else '?'
        when = time.strftime('%Y-%m-%d', time.localtime(os.path.getmtime(path)))
        rows.append((rel, when, cls, floors, problems, kit))
        for fl, p in problems:
            groups[norm(p)].append((rel, fl, p))

    # Kept short (the user: "make sure that doesn't hog too much space and to actually use it"): problems seen in the
    # last RECENT_DAYS are CURRENT and listed in full; older ones are history, one line each; runs older than that get
    # one summary line, recent runs a floor table.
    RECENT_DAYS = 7
    now = time.time()
    recent_runs = {rel for rel, when, *_ in rows if now - time.mktime(time.strptime(when, '%Y-%m-%d')) <= RECENT_DAYS * 86400}
    out = ['# What the bots saw', '',
           'Generated by `python tools/bot_digest.py` from every autoplay log under `Builds/` (logs are not in git; this file',
           'is the record). Re-run after each bot run and act on CURRENT problems: fix them or say why not. Floors: minutes,',
           'guardian minutes, kills, damage taken, near-downs (blows that would have downed the bot; it stays at 1 HP).', '',
           '## CURRENT problems (runs in the last %d days)' % RECENT_DAYS, '']
    cur = [(s, h) for s, h in groups.items() if any(x[0] in recent_runs for x in h)]
    for shape, hits in sorted(cur, key=lambda kv: -len(kv[1])):
        runs_seen = sorted({x[0] for x in hits if x[0] in recent_runs})
        out.append('- %dx: %s  (%s)' % (len(hits), hits[-1][2][:200].replace('|', '/'), ', '.join('`%s`' % r.split('/')[-2] for r in runs_seen[:4])))
    if not cur:
        out.append('- none')
    old = [(s, h) for s, h in groups.items() if not any(x[0] in recent_runs for x in h)]
    out += ['', '## History (older problems, probably fixed; top 15 by count)', '']
    for shape, hits in sorted(old, key=lambda kv: -len(kv[1]))[:15]:
        out.append('- %dx: %s' % (len(hits), hits[-1][2][:140].replace('|', '/')))
    out += ['', '## Recent runs', '']
    for rel, when, cls, floors, problems, kit in rows:
        if rel not in recent_runs:
            continue
        out.append('**`%s`** (%s, %s): ' % (rel, when, cls) + (' / '.join('F%d %.1fm g%.1f k%d t%d nd%d' % (f[0], f[1], f[2], f[3], f[5], f[7]) for f in floors) or 'no finished floors'))
        if kit:
            out.append('  - kit: ' + kit[:260].replace('|', '/'))
    out += ['', '## Older runs', '']
    for rel, when, cls, floors, problems, kit in rows:
        if rel in recent_runs:
            continue
        nd = sum(f[7] for f in floors)
        out.append('- `%s` %s %s: %d floors, %d near-downs, %d problems' % (rel, when, cls, len(floors), nd, len(problems)))
    open(OUT, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print('bot_digest: %d runs, %d problem shapes -> %s' % (len(rows), len(groups), os.path.relpath(OUT, ROOT)))


if __name__ == '__main__':
    main()
